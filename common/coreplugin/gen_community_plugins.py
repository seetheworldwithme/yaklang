#!/usr/bin/env python3
# 从 Yakit 插件导出包(539个插件.zip 解压目录，每插件一个 <uuid>.json + meta.json)生成引擎内置社区插件：
#   1. base-yak-plugin/cpNNNN__<净化名>.yak   —— 插件源码(go:embed 自动携带)
#   2. community_buildin_plugins.go           —— 映射表 + 注册逻辑(本脚本只生成数据表部分)
# is_core_plugin=true 的官方内置跳过(引擎自带)。上传者归一 Admin，原作者进贡献者字段。
# 用法: python3 gen_community_plugins.py <zip解压目录> [yaklang仓库根目录]
import json, glob, re, os, sys, unicodedata

SRC = sys.argv[1] if len(sys.argv) > 1 else '/tmp/plugins539'
ROOT = sys.argv[2] if len(sys.argv) > 2 else '.'
OUT = os.path.join(ROOT, 'common/coreplugin/base-yak-plugin')
GO_FILE = os.path.join(ROOT, 'common/coreplugin/community_buildin_plugins.go')
ASCII_OK = set(" ._-+#()&,!")

def sanitize(name):
    out = []
    for ch in name:
        if ch.isascii() and (ch.isalnum() or ch in ASCII_OK):
            out.append(ch)
        elif not ch.isascii() and unicodedata.category(ch).startswith(('L', 'N')):
            out.append(ch)
        else:
            out.append('_')
    return re.sub(r'\s+', ' ', ''.join(out)).rstrip(' .')

def gostr(s):
    return json.dumps(s, ensure_ascii=False)

existing = set(f for f in os.listdir(OUT) if not f.startswith('cp'))
for f in os.listdir(OUT):
    if f.startswith('cp') and f.endswith('.yak'):
        os.remove(os.path.join(OUT, f))

metas, idx = [], 0
for f in sorted(glob.glob(os.path.join(SRC, '*.json'))):
    if f.endswith('meta.json'): continue
    d = json.load(open(f))
    if d.get('is_core_plugin'): continue
    idx += 1
    name = d['script_name'].strip()
    fname = 'cp%04d__%s.yak' % (idx, sanitize(name))
    assert fname not in existing, 'collision: ' + fname
    existing.add(fname)
    content = d.get('content') or ''
    if not content.strip(): raise SystemExit('empty content: ' + name)
    if not content.endswith('\n'): content += '\n'
    open(os.path.join(OUT, fname), 'w', encoding='utf-8').write(content)
    tags = [t.strip() for t in re.split(r'[,，]', d.get('tags') or '') if t.strip()]
    metas.append({'file': fname, 'name': name, 'type': (d.get('type') or 'yak').strip(),
                  'help': (d.get('help') or '').strip(), 'tags': tags,
                  'contrib': (d.get('author') or '').strip()})

L = ['package coreplugin', '',
     '// Code generated by gen_community_plugins.py from 539个插件.zip (501 community plugins). DO NOT EDIT.',
     '// 社区插件内置化：上传者统一为 Admin(内置插件语义)，原作者保留在贡献者(OnlineContributors)。', '',
     'import "github.com/yaklang/yaklang/common/log"', '',
     '// communityBuildInPluginMeta 描述一个由社区插件包导入的内置插件',
     'type communityBuildInPluginMeta struct {',
     '\tFileName            string', '\tScriptName          string', '\tPluginType          string',
     '\tHelp                string', '\tTags                []string', '\tOnlineContributors  []string',
     '}', '',
     'var communityBuildInPluginMetas = []communityBuildInPluginMeta{']
for m in metas:
    parts = ['FileName: %s' % gostr(m['file']), 'ScriptName: %s' % gostr(m['name']),
             'PluginType: %s' % gostr(m['type']), 'Help: %s' % gostr(m['help'])]
    if m['tags']:
        parts.append('Tags: []string{%s}' % ', '.join(gostr(t) for t in m['tags']))
    if m['contrib']:
        parts.append('OnlineContributors: []string{%s}' % gostr(m['contrib']))
    L.append('\t{%s},' % ', '.join(parts))
L += ['}', '',
      '// communityBuildInPluginFileByName 插件名 -> 净化后的 embed 文件名(GetCorePluginData 兜底查找用)',
      'var communityBuildInPluginFileByName = map[string]string{']
for m in metas:
    L.append('\t%s: %s,' % (gostr(m['name']), gostr(m['file'])))
L += ['}', '',
      '// registerCommunityBuildInPlugins 注册社区内置插件(内容来自 base-yak-plugin/cpNNNN__*.yak)',
      'func registerCommunityBuildInPlugins() {',
      '\tfor _, meta := range communityBuildInPluginMetas {',
      '\t\tcodeBytes, err := basePluginFS.ReadFile("base-yak-plugin/" + meta.FileName)',
      '\t\tif err != nil || len(codeBytes) == 0 {',
      '\t\t\tlog.Errorf("read community buildin plugin [%v] %v failed: %v", meta.ScriptName, meta.FileName, err)',
      '\t\t\tcontinue', '\t\t}',
      '\t\topts := []pluginOption{}',
      '\t\tif meta.Help != "" {', '\t\t\topts = append(opts, withPluginHelp(meta.Help))', '\t\t}',
      '\t\tif len(meta.Tags) > 0 {', '\t\t\topts = append(opts, withPluginTags(meta.Tags))', '\t\t}',
      '\t\tif len(meta.OnlineContributors) > 0 {',
      '\t\t\topts = append(opts, withPluginAuthors(meta.OnlineContributors...))', '\t\t}',
      '\t\tregisterBuildInPluginContent(meta.PluginType, meta.ScriptName, string(codeBytes), opts...)',
      '\t}', '}', '']
open(GO_FILE, 'w', encoding='utf-8').write('\n'.join(L))
print('written %d community plugins' % idx)
